const catalogs = { de, en };

function currentLang() {
  const lang = (document.documentElement.lang || 'de').slice(0, 2).toLowerCase();
  return catalogs[lang] ? lang : 'de';
}

export function t(key) {
  const catalog = catalogs[currentLang()];
  if (key in catalog) return catalog[key];
  if (key in de) return de[key];
  return key; // unbekannter Backend-Code: lieber roh anzeigen als verschlucken
}
